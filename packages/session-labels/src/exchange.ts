import { createHash } from "node:crypto";

import type { CanonicalTrace, GenAiInputMessage, GenAiMessagePart } from "@traice/domain";

// One canonical trace is one provider exchange. Coding agents resend the whole
// conversation on every call, so a view keeps only what is new in this
// exchange: the human's latest words, or the results of the tool calls the
// agent made last time, plus whatever the agent said or called in response.

export interface ToolCallView {
  readonly arguments: unknown;
  readonly id: string;
  readonly name: string;
}

export interface AnsweredCall extends ToolCallView {
  readonly response: string;
}

export interface ExchangeView {
  readonly answeredCalls: readonly AnsweredCall[];
  readonly assistantText: string;
  readonly capturedAt: string;
  readonly client: string;
  readonly doneClaim: boolean;
  readonly humanText?: string;
  readonly outputCalls: readonly ToolCallView[];
  readonly projectScopeId?: string;
  readonly sessionKey: string;
  readonly traceId: string;
}

const responseHeadChars = 2_000;
const responseTailChars = 4_000;

const finishedReasons = new Set(["completed", "end_turn", "stop", "stop_sequence"]);

// Text the client injects into user messages that the human never typed.
const injectedBlock = /<(system-reminder|local-command-stdout|local-command-stderr)>[\s\S]*?<\/\1>/gu;
const injectedMessage = /^\s*(<environment_context>|<user_instructions>|<permissions instructions>|# AGENTS\.md instructions|Caveat: The messages below were generated by the user while running local commands)/u;

const textOf = (parts: readonly GenAiMessagePart[]): string =>
  parts
    .filter((part) => part.type === "text" && typeof part.content === "string")
    .map((part) => part.content as string)
    .join("\n")
    .trim();

const humanTextOf = (messages: readonly GenAiInputMessage[]): string | undefined => {
  const pieces = messages
    .filter((message) => message.role === "user")
    .flatMap((message) => message.parts)
    .filter((part) => part.type === "text" && typeof part.content === "string")
    .map((part) => (part.content as string).replace(injectedBlock, "").trim())
    .filter((text) => text.length > 0 && !injectedMessage.test(text));
  const text = pieces.join("\n").trim();
  return text.length > 0 ? text : undefined;
};

export const flattenResponse = (value: unknown): string => {
  if (typeof value === "string") return value;
  if (Array.isArray(value)) return value.map(flattenResponse).filter(Boolean).join("\n");
  if (value && typeof value === "object") {
    const record = value as Readonly<Record<string, unknown>>;
    if (typeof record.text === "string") return record.text;
    if (typeof record.output === "string") return record.output;
    if (record.content !== undefined) return flattenResponse(record.content);
    return JSON.stringify(value);
  }
  return value === undefined || value === null ? "" : String(value);
};

export const clip = (text: string, head: number, tail: number): string =>
  text.length <= head + tail ? text : `${text.slice(0, head)}\n…\n${text.slice(-tail)}`;

const toolCalls = (parts: readonly GenAiMessagePart[]): readonly ToolCallView[] =>
  parts.flatMap((part) =>
    part.type === "tool_call" && typeof part.id === "string" && typeof part.name === "string"
      ? [{ arguments: part.arguments, id: part.id, name: part.name }]
      : []
  );

const sessionKeyOf = (trace: CanonicalTrace, input: readonly GenAiInputMessage[]): string =>
  createHash("sha256")
    .update(JSON.stringify({
      // The first message is the only one every exchange in a conversation shares.
      head: input.slice(0, 1),
      run: trace.traice.captureRunId ?? null,
      system: trace.span.attributes["gen_ai.system_instructions"] ?? null,
    }))
    .digest("hex");

export const viewExchange = (trace: CanonicalTrace, traceId = trace.traice.traceId): ExchangeView => {
  const attributes = trace.span.attributes;
  const input = attributes["gen_ai.input.messages"] ?? [];
  const output = attributes["gen_ai.output.messages"] ?? [];
  let lastAssistant = -1;
  for (let index = input.length - 1; index >= 0; index -= 1) {
    if (input[index]?.role === "assistant") {
      lastAssistant = index;
      break;
    }
  }
  const fresh = input.slice(lastAssistant + 1);
  const pendingCalls = lastAssistant >= 0 ? toolCalls(input[lastAssistant]?.parts ?? []) : [];
  const responses = new Map(
    fresh.flatMap((message) => message.parts).flatMap((part) =>
      part.type === "tool_call_response" && typeof part.id === "string"
        ? [[part.id, flattenResponse(part.response)] as const]
        : []
    )
  );
  const answeredCalls = pendingCalls.flatMap((call) => {
    const response = responses.get(call.id);
    return response === undefined
      ? []
      : [{ ...call, response: clip(response, responseHeadChars, responseTailChars) }];
  });
  const outputParts = output.flatMap((message) => message.parts);
  const outputCalls = toolCalls(outputParts);
  const assistantText = textOf(outputParts);
  const reasons = output.map((message) => message.finish_reason);
  const humanText = humanTextOf(fresh);
  return {
    answeredCalls,
    assistantText,
    capturedAt: trace.traice.capturedAt,
    client: trace.traice.client,
    doneClaim: outputCalls.length === 0
      && assistantText.length > 0
      && reasons.some((reason) => finishedReasons.has(reason)),
    ...(humanText === undefined ? {} : { humanText }),
    outputCalls,
    ...(trace.traice.projectScopeId === undefined ? {} : { projectScopeId: trace.traice.projectScopeId }),
    sessionKey: sessionKeyOf(trace, input),
    traceId,
  };
};
